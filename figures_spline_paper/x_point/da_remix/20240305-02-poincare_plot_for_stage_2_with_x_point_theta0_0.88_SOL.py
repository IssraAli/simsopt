# Same as simsopt's compute_fieldlines, but also accept an input phi0 array.
def compute_fieldlines(
    field,
    xyz_inits,
    tmax=10000,
    tol=1e-7,
    phis=[],
    stopping_criteria=[],
    comm=None,
):
    r"""
    Compute magnetic field lines by solving

    .. math::

        [\dot x, \dot y, \dot z] = B(x, y, z)

    Args:
        field: the magnetic field :math:`B`
        R0: list of radial components of initial points
        Z0: list of vertical components of initial points
        tmax: for how long to trace. will do roughly ``|B|*tmax/(2*pi*r0)`` revolutions of the device
        tol: tolerance for the adaptive ode solver
        phis: list of angles in [0, 2pi] for which intersection with the plane
              corresponding to that phi should be computed
        stopping_criteria: list of stopping criteria, mostly used in
                           combination with the ``LevelsetStoppingCriterion``
                           accessed via :obj:`simsopt.field.tracing.SurfaceClassifier`.

    Returns: 2 element tuple containing
        - ``res_tys``:
            A list of numpy arrays (one for each particle) describing the
            solution over time. The numpy array is of shape (ntimesteps, 4).
            Each row contains the time and
            the position, i.e.`[t, x, y, z]`.
        - ``res_phi_hits``:
            A list of numpy arrays (one for each particle) containing
            information on each time the particle hits one of the phi planes or
            one of the stopping criteria. Each row of the array contains
            `[time, idx, x, y, z]`, where `idx` tells us which of the `phis`
            or `stopping_criteria` was hit.  If `idx>=0`, then `phis[int(idx)]`
            was hit. If `idx<0`, then `stopping_criteria[int(-idx)-1]` was hit.
    """
    nlines = xyz_inits.shape[0]
    # assert len(R0) == len(Z0)
    # assert len(R0) == len(phi0)
    # nlines = len(R0)
    # xyz_inits = np.zeros((nlines, 3))
    # R0 = np.asarray(R0)
    # phi0 = np.asarray(phi0)
    # xyz_inits[:, 0] = R0 * np.cos(phi0)
    # xyz_inits[:, 1] = R0 * np.sin(phi0)
    # xyz_inits[:, 2] = np.asarray(Z0)
    res_tys = []
    res_phi_hits = []
    first, last = parallel_loop_bounds(comm, nlines)
    for i in range(first, last):
        res_ty, res_phi_hit = sopp.fieldline_tracing(
            field,
            xyz_inits[i, :],
            tmax,
            tol,
            phis=phis,
            stopping_criteria=stopping_criteria,
        )
        res_tys.append(np.asarray(res_ty))
        res_phi_hits.append(np.asarray(res_phi_hit))
        dtavg = res_ty[-1][0] / len(res_ty)
        logger.debug(
            f"{i + 1:3d}/{nlines}, t_final={res_ty[-1][0]}, average timestep {dtavg:.10f}s"
        )
    if comm is not None and comm.Get_size() > 1:
        # Skip the no-op gather on a single rank: with tmax_fl this large,
        # most trajectories never hit a stopping criterion, so res_tys is
        # huge, and mpi4py's pickle-based allgather chokes on the buffer
        # size even when there's nothing to gather (MPI_ERR_ARG).
        res_tys = [i for o in comm.allgather(res_tys) for i in o]
        res_phi_hits = [i for o in comm.allgather(res_phi_hits) for i in o]
    return res_tys, res_phi_hits


def particles_to_vtk(res_tys, filename):
    """
    Export particle tracing or field lines to a vtk file.
    Expects that the xyz positions can be obtained by ``xyz[:, 1:4]``.
    """
    from pyevtk.hl import polyLinesToVTK

    # res_tys0 = res_tys.copy()
    res_tys_stellsym = []
    for xyz in res_tys:
        xyz_flipped = xyz.copy()
        # Flip y and z, not x
        xyz_flipped[:, 2] = -xyz[:, 2]
        xyz_flipped[:, 3] = -xyz[:, 3]
        res_tys_stellsym.append(xyz_flipped)

    res_tys0 = res_tys + res_tys_stellsym

    res_tys = []
    for xyz in res_tys0:
        # xyz = res_tys0[j]
        for i in range(nfp):
            # phi = np.atan2(xyz[:, 2], xyz[:, 1])
            xyz_new = np.zeros_like(xyz)
            angle = i * 2 * np.pi / nfp
            xyz_new[:, 0] = xyz[:, 0]
            xyz_new[:, 1] = xyz[:, 1] * np.cos(angle) + xyz[:, 2] * np.sin(
                angle
            )
            xyz_new[:, 2] = xyz[:, 1] * -(np.sin(angle)) + xyz[:, 2] * np.cos(
                angle
            )
            xyz_new[:, 3] = xyz[:, 3]
            res_tys.append(xyz_new)

    t = np.concatenate([xyz[:, 0] for xyz in res_tys])
    x = np.concatenate([xyz[:, 1] for xyz in res_tys])
    y = np.concatenate([xyz[:, 2] for xyz in res_tys])
    z = np.concatenate([xyz[:, 3] for xyz in res_tys])
    ppl = np.asarray([xyz.shape[0] for xyz in res_tys])
    data = np.concatenate(
        [i * np.ones((res_tys[i].shape[0],)) for i in range(len(res_tys))]
    )
    rand = np.concatenate(
        [
            np.random.rand() * np.ones((res_tys[i].shape[0],))
            for i in range(len(res_tys))
        ]
    )
    pointData = {"idx": data, "time": t, "rand": rand}
    polyLinesToVTK(filename, x, y, z, pointsPerLine=ppl, pointData=pointData)


def plot_poincare_data(
    fieldlines_phi_hits,
    phis,
    filename,
    mark_lost=False,
    aspect="equal",
    dpi=300,
    xlims=None,
    ylims=None,
    s=2,
    marker="o",
):
    """
    Create a poincare plot. Usage:

    .. code-block::

        phis = np.linspace(0, 2*np.pi/nfp, nphis, endpoint=False)
        res_tys, res_phi_hits = compute_fieldlines(
            bsh, R0, Z0, tmax=1000, phis=phis, stopping_criteria=[])
        plot_poincare_data(res_phi_hits, phis, '/tmp/fieldlines.png')

    Requires matplotlib to be installed.

    """
    plt.rc("font", size=7)
    # nrowcol = ceil(sqrt(len(phis)))
    nrowcol = 2
    plt.figure()
    fig, axs = plt.subplots(nrowcol, nrowcol, figsize=(8, 5))
    for ax in axs.ravel():
        ax.set_aspect(aspect)
    color = None
    prop_cycle = plt.rcParams["axes.prop_cycle"]
    colors = prop_cycle.by_key()["color"]
    # for i in range(len(phis)):
    for i in range(4):
        row = i // nrowcol
        col = i % nrowcol

        # Plot only the crossover-leg u values each twin actually
        # contributed to the coil optimization's flux grid (see
        # compute_uphi_grid_interpolated in stage_2_scan_twin.py) --
        # NOT the full closed-loop boundary, most of which the flux
        # objective never touched. `phis[i]` is in RADIANS
        # (compute_fieldlines' own convention), but
        # compute_uphi_grid_interpolated's phis are normalized [0, 1)
        # fractions -- dividing here is required, not optional (only
        # phi=0 would happen to line up otherwise).
        #
        # compute_uphi_grid_interpolated only accepts phi within
        # spline_surf's own fundamental domain (one field-period half,
        # e.g. [0, 0.25] here) -- Poincare sections span a full field
        # period, so phis[i]/(2*pi) can exceed that (e.g. 0.375 at
        # phi=0.75*pi). Passing it straight through would silently
        # clamp to the wrong, non-mirrored geometry (verified: this
        # was the cause of the boundary outline not matching the 3D
        # flux_grids.png plot, which never leaves the fundamental
        # domain). reduce_phi_to_fundamental_domain +
        # mirror_position_to_phi correctly wrap/mirror instead.
        phi_frac_true = phis[i] / (2 * np.pi)
        phi_frac, mirrored = reduce_phi_to_fundamental_domain(
            spline_surf, phi_frac_true
        )
        for surf, keep_between, color in (
            (surf_outboard, outboard_is_between, "tab:red"),
            (surf_inboard, not outboard_is_between, "tab:blue"),
        ):
            grid = compute_uphi_grid_interpolated(
                spline_surf,
                geometry,
                LEG_FRACTION,
                keep_between,
                [phi_frac],
                ntheta=NTHETA,
            )
            pos = np.zeros((NTHETA, 3))
            surf.gamma_lin(
                pos, grid["phi"].reshape(-1), grid["theta"].reshape(-1)
            )
            if mirrored:
                pos = mirror_position_to_phi(pos, phi_frac_true)
            r_interp = np.hypot(pos[:, 0], pos[:, 1])
            z_interp = pos[:, 2]
            axs[row, col].plot(r_interp, z_interp, linewidth=1, c=color)

        axs[row, col].grid(True, linewidth=0.5)

        # if i != len(phis) - 1:
        if i != 4 - 1:
            axs[row, col].set_title(
                f"$\\phi = {phis[i] / np.pi:.3f}\\pi$ ", loc="left", y=0.0
            )
        else:
            axs[row, col].set_title(
                f"$\\phi = {phis[i] / np.pi:.3f}\\pi$ ", loc="right", y=0.0
            )
        if row == nrowcol - 1:
            axs[row, col].set_xlabel("$R$")
        if col == 0:
            axs[row, col].set_ylabel("$Z$")
        if col == 1:
            axs[row, col].set_yticklabels([])
        if xlims is not None:
            axs[row, col].set_xlim(xlims)
        if ylims is not None:
            axs[row, col].set_ylim(ylims)
        for j in range(len(fieldlines_phi_hits)):
            if fieldlines_phi_hits[j].size == 0:
                continue
            if mark_lost:
                lost = fieldlines_phi_hits[j][-1, 1] < 0
                color = "r" if lost else "g"
            phi_hit_codes = fieldlines_phi_hits[j][:, 1]
            condition = np.logical_and(
                phi_hit_codes >= 0, np.mod(phi_hit_codes, 4) == i
            )
            indices = np.where(condition)[0]
            data_this_phi = fieldlines_phi_hits[j][indices, :]
            if data_this_phi.size == 0:
                continue
            r = np.sqrt(data_this_phi[:, 2] ** 2 + data_this_phi[:, 3] ** 2)
            color = colors[j % len(colors)]
            axs[row, col].scatter(
                r,
                data_this_phi[:, 4],
                marker=marker,
                s=s,
                linewidths=0,
                c=color,
            )

            # stellarator-symmetric points:
            new_row = row
            if i == 1 or i == 3:
                new_row = 1 - row

            axs[new_row, col].scatter(
                r,
                -data_this_phi[:, 4],
                marker=marker,
                s=s,
                linewidths=0,
                c=color,
            )

        # plt.rc('axes', axisbelow=True)

    plt.figtext(
        0.5,
        0.995,
        os.path.abspath(coils_filename),
        ha="center",
        va="top",
        fontsize=4,
    )
    plt.figtext(0.5, 0.005, bottom_str, ha="center", va="bottom", fontsize=6)
    plt.tight_layout()
    plt.savefig(filename, dpi=dpi)


