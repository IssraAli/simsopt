def _sol_seed_points(surf, phi_flat, theta_flat, delta):
    """Points `delta` outward, past the LCFS into the SOL, along surf's
    own unit normal (which points inward, hence the minus sign) --
    replaces the old SurfaceHelicalArc `radius_a + delta` trick, which
    has no direct equivalent for SurfaceBSpline's dofs."""
    pos, g1, g2 = surf._gamma_and_derivs(phi_flat, theta_flat, max_deriv=1)
    normal = np.cross(g1, g2, axis=1)
    unitnormal = normal / np.linalg.norm(normal, axis=1, keepdims=True)
    return pos - delta * unitnormal


